struct StressRegion {
    Vec3 minimum{}, maximum{};
    float utilization{};
};
inline uint32_t stressColor(float utilization) {
    float t = std::clamp(utilization, 0.f, 1.f);
    Vec3 low{.12f, .85f, .3f}, mid{1.f, .8f, .08f}, high{1.f, .12f, .04f};
    Vec3 c = t < .5f ? low + (mid - low) * (t * 2) : mid + (high - mid) * ((t - .5f) * 2);
    return (uint32_t(c.x * 255) << 24) | (uint32_t(c.y * 255) << 16) | (uint32_t(c.z * 255) << 8) |
           255;
}
